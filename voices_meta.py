def build_voice_catalog(voice_names: list[str]) -> list[dict]:
    catalog = []
    for name in sorted(voice_names):
        prefix = name[:2]
        language, lang_code, gender, accent = PREFIX_META.get(
            prefix, ("Other", "en-us", "Neutral", "INTL")
        )
        raw_label = name[3:].replace("_", " ").title() if "_" in name else name.title()
        grade, desc = VOICE_DESCRIPTIONS.get(name, ("B", f"{language} {gender.lower()} voice"))
        catalog.append(
            {
                "id": name,
                "name": raw_label,
                "language": language,
                "lang_code": lang_code,
                "gender": gender,
                "accent": accent,
                "grade": grade,
                "description": desc,
            }
        )
    # Sort featured English voices first
    grade_order = {"A": 0, "A-": 1, "B": 2, "B-": 3, "C+": 4, "C": 5, "C-": 6, "D+": 7, "D": 8, "D-": 9, "F+": 10}
    catalog.sort(key=lambda v: (0 if v["lang_code"].startswith("en") else 1, grade_order.get(v["grade"], 5), v["id"]))
    return catalog
